"""
FastAPI service for the Art Auction Price Prediction model.

Loads the best model, scaler, and feature/category vocabularies produced by
summative/linear_regression/multivariate.ipynb, and exposes:
  - GET  /              health check
  - POST /predict       predict an artwork's auction price
  - POST /retrain       retrain the model from an uploaded CSV of new data
  - GET  /docs           Swagger UI (auto-generated by FastAPI)
"""

import os
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, HTTPException, UploadFile, File
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LinearRegression, SGDRegressor
from sklearn.ensemble import RandomForestRegressor
from sklearn.tree import DecisionTreeRegressor
from sklearn.metrics import mean_squared_error

# ---------------------------------------------------------------------------
# Load trained artifacts
# ---------------------------------------------------------------------------
ARTIFACT_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(ARTIFACT_DIR, "..", "linear_regression", "best_model.joblib")
SCALER_PATH = os.path.join(ARTIFACT_DIR, "..", "linear_regression", "scaler.joblib")
FEATURE_COLUMNS_PATH = os.path.join(ARTIFACT_DIR, "..", "linear_regression", "feature_columns.joblib")
KNOWN_MOVEMENTS_PATH = os.path.join(ARTIFACT_DIR, "..", "linear_regression", "known_movements.joblib")
KNOWN_PERIODS_PATH = os.path.join(ARTIFACT_DIR, "..", "linear_regression", "known_periods.joblib")

model = joblib.load(MODEL_PATH)
scaler = joblib.load(SCALER_PATH)
FEATURE_COLUMNS = joblib.load(FEATURE_COLUMNS_PATH)
KNOWN_MOVEMENTS = joblib.load(KNOWN_MOVEMENTS_PATH)
KNOWN_PERIODS = joblib.load(KNOWN_PERIODS_PATH)
NUMERIC_COLS = ["year_clean", "condition_score"]

# Build a Literal type dynamically so Swagger UI shows a dropdown of valid values
PeriodType = Literal[tuple(KNOWN_PERIODS)]
MovementType = Literal[tuple(KNOWN_MOVEMENTS)]

# ---------------------------------------------------------------------------
# App + CORS
# ---------------------------------------------------------------------------
app = FastAPI(
    title="Art Auction Price Prediction API",
    description="Predicts the auction sale price of an artwork from its "
                 "creation year, signing status, condition, artist recognition, "
                 "period, and movement.",
    version="1.0.0",
)

# CORS reasoning:
#   - allow_origins is an explicit allow-list (not "*"), because this API
#     accepts POST requests with real prediction data, and a wildcard origin
#     combined with allow_credentials would let any website silently call it
#     on a user's behalf. The Flutter web build and local dev server are the
#     only clients that should be trusted; everything else is rejected by
#     the browser's CORS check before the request body is even sent.
#   - allow_methods is restricted to GET/POST since this API never needs
#     PUT/DELETE/PATCH.
#   - allow_headers is restricted to Content-Type, the only custom header
#     the Flutter client sends.
#   - allow_credentials is False because no cookies/auth headers are used;
#     turning it on would be unnecessary attack surface.
ALLOWED_ORIGINS = [
    "http://localhost:3000",
    "http://localhost:8080",
    "http://127.0.0.1:3000",
    # TODO: add your deployed Flutter web origin here once you have one,
    # e.g. "https://your-flutter-app.web.app"
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


# ---------------------------------------------------------------------------
# Request / response schemas
# ---------------------------------------------------------------------------
class ArtworkFeatures(BaseModel):
    year_clean: float = Field(
        ..., ge=1800, le=2026,
        description="Approximate year the artwork was created (1800-2026)."
    )
    is_signed: int = Field(
        ..., ge=0, le=1,
        description="1 if the artwork is signed, 0 if not."
    )
    condition_score: int = Field(
        ..., ge=0, le=3,
        description="0 = damage/wear noted, 1 = good, 2 = very good, 3 = excellent."
    )
    artist_known: int = Field(
        ..., ge=0, le=1,
        description="1 if the artist is well-represented in the training market data, 0 otherwise."
    )
    period: PeriodType = Field(..., description="Art-historical period.")
    movement: MovementType = Field(..., description="Art movement/style.")

    model_config = {
        "json_schema_extra": {
            "example": {
                "year_clean": 2015,
                "is_signed": 1,
                "condition_score": 3,
                "artist_known": 1,
                "period": "Contemporary",
                "movement": "Abstract",
            }
        }
    }


class PredictionResponse(BaseModel):
    predicted_price_usd: float
    predicted_price_formatted: str


class RetrainResponse(BaseModel):
    message: str
    rows_used: int
    previous_test_mse: float
    new_test_mse: float
    model_improved: bool


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def build_feature_row(features: ArtworkFeatures) -> pd.DataFrame:
    """Turn a validated request into a one-row DataFrame matching training columns."""
    row = {col: 0 for col in FEATURE_COLUMNS}
    row["year_clean"] = features.year_clean
    row["is_signed"] = features.is_signed
    row["condition_score"] = features.condition_score
    row["artist_known"] = features.artist_known

    period_col = f"period_clean_{features.period}"
    if period_col in row:
        row[period_col] = 1
    # if period is the dropped baseline category, all period_clean_* stay 0 — correct

    movement_col = f"movement_grouped_{features.movement}"
    if movement_col in row:
        row[movement_col] = 1
    # if movement is the dropped baseline category, all movement_grouped_* stay 0 — correct

    df_row = pd.DataFrame([row], columns=FEATURE_COLUMNS)
    df_row[NUMERIC_COLS] = scaler.transform(df_row[NUMERIC_COLS])
    return df_row


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
@app.get("/")
def health_check():
    return {"status": "ok", "message": "Art Price Prediction API is running. See /docs for Swagger UI."}


@app.post("/predict", response_model=PredictionResponse)
def predict(features: ArtworkFeatures):
    try:
        row = build_feature_row(features)
        log_price = model.predict(row)[0]
        price = float(np.expm1(log_price))
        price = max(price, 0.0)
        return PredictionResponse(
            predicted_price_usd=round(price, 2),
            predicted_price_formatted=f"${price:,.2f}",
        )
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Prediction failed: {e}")


@app.post("/retrain", response_model=RetrainResponse)
async def retrain(file: UploadFile = File(...)):
    """
    Retrain the model when new labeled data is available.

    Expects a CSV upload with the same raw columns as the original training
    data (price, yearCreation, signed, condition, artist, period, movement).
    Retrains a fresh Random Forest, compares it to the currently deployed
    model on a held-out split, and only replaces the deployed model if the
    new one performs at least as well.
    """
    global model

    if not file.filename.endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")

    try:
        new_df = pd.read_csv(file.file)
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Could not read CSV: {e}")

    required_cols = {"price", "yearCreation", "signed", "condition", "artist", "period", "movement"}
    missing = required_cols - set(new_df.columns)
    if missing:
        raise HTTPException(status_code=400, detail=f"CSV missing required columns: {missing}")

    # --- same cleaning pipeline as the training notebook ---
    import re

    def clean_price(x):
        if pd.isna(x):
            return np.nan
        x = str(x).replace("USD", "").strip().replace(".", "")
        try:
            return float(x)
        except ValueError:
            return np.nan

    era_map = {
        "first half 20th century": 1925, "mid 20th century": 1950,
        "second half 20th century": 1975, "late 20th century": 1985,
        "19th century": 1850, "second half 19th century": 1875,
    }

    def clean_year(x):
        if pd.isna(x) or str(x).strip() == "[nan]":
            return np.nan
        s = str(x).strip().lower()
        if s in era_map:
            return era_map[s]
        years = re.findall(r"(1[89]\d{2}|20[0-2]\d)", s)
        if years:
            return sum(int(y) for y in years) / len(years)
        return np.nan

    new_df["price_usd"] = new_df["price"].apply(clean_price)
    new_df["year_clean"] = new_df["yearCreation"].apply(clean_year)
    new_df["is_signed"] = new_df["signed"].apply(lambda x: 0 if pd.isna(x) or str(x).strip() == "[nan]" else 1)

    def condition_score(x):
        if pd.isna(x) or str(x).strip() == "[nan]":
            return np.nan
        s = str(x).lower()
        if "excellent" in s:
            return 3
        elif "very good" in s:
            return 2
        elif "good" in s:
            return 1
        return 0

    new_df["condition_score"] = new_df["condition"].apply(condition_score)
    artist_counts = new_df["artist"].value_counts()
    new_df["artist_known"] = new_df["artist"].map(lambda a: 1 if artist_counts.get(a, 0) >= 3 else 0)
    new_df["period_clean"] = new_df["period"].str.strip().replace("[nan]", np.nan)
    new_df["movement_clean"] = new_df["movement"].str.strip().replace("[nan]", np.nan)
    new_df["movement_grouped"] = new_df["movement_clean"].apply(
        lambda m: m if m in KNOWN_MOVEMENTS else "Other"
    )
    new_df.loc[~new_df["period_clean"].isin(KNOWN_PERIODS), "period_clean"] = np.nan

    model_df = new_df[["price_usd", "year_clean", "is_signed", "condition_score",
                        "artist_known", "period_clean", "movement_grouped"]].copy()
    model_df = model_df.dropna(subset=["price_usd", "year_clean", "condition_score", "period_clean"])

    if len(model_df) < 20:
        raise HTTPException(
            status_code=400,
            detail=f"Only {len(model_df)} usable rows after cleaning; need at least 20 to retrain.",
        )

    model_df["log_price"] = np.log1p(model_df["price_usd"])
    model_df = pd.get_dummies(model_df, columns=["period_clean", "movement_grouped"], drop_first=True)

    # Align to the original training columns exactly (add any missing dummy cols as 0)
    for col in FEATURE_COLUMNS:
        if col not in model_df.columns:
            model_df[col] = 0
    X_new = model_df[FEATURE_COLUMNS]
    y_new = model_df["log_price"]

    X_train, X_test, y_train, y_test = train_test_split(X_new, y_new, test_size=0.2, random_state=42)

    new_scaler = StandardScaler()
    X_train_scaled = X_train.copy()
    X_test_scaled = X_test.copy()
    X_train_scaled[NUMERIC_COLS] = new_scaler.fit_transform(X_train[NUMERIC_COLS])
    X_test_scaled[NUMERIC_COLS] = new_scaler.transform(X_test[NUMERIC_COLS])

    candidate = RandomForestRegressor(n_estimators=300, max_depth=10, random_state=42)
    candidate.fit(X_train_scaled, y_train)
    new_test_mse = mean_squared_error(y_test, candidate.predict(X_test_scaled))

    # Compare against current deployed model on the same held-out split
    X_test_scaled_for_old = X_test.copy()
    X_test_scaled_for_old[NUMERIC_COLS] = scaler.transform(X_test[NUMERIC_COLS])
    old_test_mse = mean_squared_error(y_test, model.predict(X_test_scaled_for_old))

    improved = new_test_mse <= old_test_mse
    if improved:
        model = candidate
        joblib.dump(model, MODEL_PATH)
        joblib.dump(new_scaler, SCALER_PATH)

    return RetrainResponse(
        message="Model retrained and deployed." if improved else
                "Retrained model did not outperform the current model; keeping existing model.",
        rows_used=len(model_df),
        previous_test_mse=round(float(old_test_mse), 4),
        new_test_mse=round(float(new_test_mse), 4),
        model_improved=improved,
    )
